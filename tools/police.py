def capitale_accent(base, haut):
    """Majuscule ramenée à 6 lignes (ligne 3 retirée) sur les lignes 2-7, accent ligne 0-1."""
    r = G[base][:7]
    # retirer une ligne EN DOUBLE (jamais la barre du E / du A : « Élém » s'affichait « Ćlém », 21/11)
    i = next(k for k in range(1, 6) if r[k] == r[k + 1])
    r = r[:i] + r[i + 1:]
    return [haut[0] if haut[0] != X else X, haut[1]] + r



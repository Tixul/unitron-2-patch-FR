def tuile(rows):
    out = bytearray()
    for r in rows:
        w = 0
        for x in range(8):
            v = TRACE if (1 <= x <= 5 and r[x - 1] == '#') else FOND
            w |= v << (14 - 2 * x)
        out += bytes([w & 0xFF, w >> 8])
    return bytes(out)


def appliquer(rom):
    """Grave tous les glyphes FR ; renvoie la liste des codes écrits."""
    faits = []
    for ch, code in T.FR.items():
        if ch in G:
            p = POLICE + 16 * (code - 1)
            rom[p:p + 16] = tuile(G[ch])
            faits.append(code)
    manque = [ch for ch, c in T.FR.items() if ch not in G and c < 0x53 and ch != ' ']
    assert not manque, manque
    return faits


def planche(rom, chemin, texte=None):
    from PIL import Image
    texte = texte or ''.join(c for c in T.FR if c != ' ')
    Z = 4
    lignes = [texte[i:i + 20] for i in range(0, len(texte), 20)]
    im = Image.new('RGB', (20 * 8 * Z, len(lignes) * 8 * Z), (0, 0, 0))
    px = im.load()
    for ly, l in enumerate(lignes):
        for k, ch in enumerate(l):
            p = POLICE + 16 * (T.FR[ch] - 1)
            for y in range(8):
                w = rom[p + 2 * y] | rom[p + 2 * y + 1] << 8
                for x in range(8):
                    v = (w >> (14 - 2 * x)) & 3
                    col = (255, 255, 255) if v == TRACE else (30, 30, 60)
                    for a in range(Z):
                        for b in range(Z):
                            px[(k * 8 + x) * Z + a, (ly * 8 + y) * Z + b] = col
    im.save(chemin)


